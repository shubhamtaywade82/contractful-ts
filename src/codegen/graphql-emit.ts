/**
 * GraphQL SDL → typed TypeScript client.
 *
 * Emits, from one schema document:
 * - `types.ts` — interfaces for object/input types and enums.
 * - `client.ts` — one typed method per Query/Mutation field, executing a
 *   generated full-selection document (depth-capped, cycle-safe) through
 *   the contractful-ts HTTP transport.
 * - `subscriptions.ts` — one typed method per Subscription field over the
 *   graphql-transport-ws client from `contractful-ts/events`.
 *
 * Selection strategy: every field is selected recursively up to `maxDepth`
 * levels of object nesting; types already present on the current selection
 * path are cut — both from the document and from the mirrored result type —
 * which keeps documents finite on cyclic schemas. Object fields whose
 * selection was cut are omitted entirely (a bare object field would be an
 * invalid document).
 */

import { toPascalCase } from './openapi.js';
import { parseGraphQLSdl } from './graphql.js';
import type { EmittedFile, EmitOptions } from './emitter.js';
import type { GqlArg, GqlDocument, GqlField, GqlTypeRef } from './graphql.js';

export interface GraphQLEmitOptions extends EmitOptions {
  /** Maximum object-nesting depth of generated selections. Default `3`. */
  maxDepth?: number;
  /** Default endpoint used by the generated HTTP client. */
  base?: string;
  /** Default WebSocket URL used by the generated subscriptions client. */
  wsUrl?: string;
  /** Overrides the events module specifier (default `${importFrom}/events`). */
  eventsImportFrom?: string;
}

/** Selection tree mirroring the generated documents. */
interface SelectionNode {
  field: GqlField;
  children?: SelectionNode[];
}

/** Parses SDL text and emits the client files in one step. */
export function emitGraphqlFromSdl(
  sdlText: string,
  options: GraphQLEmitOptions = {},
): { files: EmittedFile[]; doc: GqlDocument } {
  const doc = parseGraphQLSdl(sdlText);
  return { files: emitGraphql(doc, options), doc };
}

export function emitGraphql(doc: GqlDocument, options: GraphQLEmitOptions = {}): EmittedFile[] {
  const importFrom = options.importFrom ?? 'contractful-ts';
  const maxDepth = options.maxDepth ?? 3;
  const base = options.base ?? 'https://example.com/graphql';
  const wsUrl = options.wsUrl ?? 'wss://example.com/graphql';
  const origin = options.specOrigin ?? 'GraphQL schema';

  const hasOperations = doc.queries.length > 0 || doc.mutations.length > 0;
  if (!hasOperations && doc.subscriptions.length === 0) {
    throw new Error('GraphQL schema declares no Query, Mutation or Subscription operations.');
  }

  const files: EmittedFile[] = [];
  files.push({ path: 'types.ts', content: emitTypes(doc, origin) });
  if (hasOperations) {
    files.push({ path: 'client.ts', content: emitClient(doc, importFrom, base, maxDepth, origin) });
  }
  if (doc.subscriptions.length > 0) {
    files.push({
      path: 'subscriptions.ts',
      content: emitSubscriptions(doc, importFrom, options.eventsImportFrom ?? `${importFrom}/events`, wsUrl, maxDepth, origin),
    });
  }
  files.push({
    path: 'index.ts',
    content: [
      `// Auto-generated by contractful-gen from ${origin} — DO NOT EDIT.`,
      `export * from './types.js';`,
      ...(hasOperations ? [`export * from './client.js';`] : []),
      ...(doc.subscriptions.length > 0 ? [`export * from './subscriptions.js';`] : []),
      '',
    ].join('\n'),
  });
  return files;
}

/* -------------------------------------------------------------------------- */
/* TypeScript type mapping                                                     */
/* -------------------------------------------------------------------------- */

const BUILTIN_SCALARS: Record<string, string> = {
  ID: 'string',
  String: 'string',
  Int: 'number',
  Float: 'number',
  Boolean: 'boolean',
};

function tsTypeOf(ref: GqlTypeRef, doc: GqlDocument): string {
  const inner: string = (() => {
    if (ref.kind === 'list') return `Array<${tsTypeOf(ref.of!, doc)}>`;
    const name = ref.name!;
    if (BUILTIN_SCALARS[name] !== undefined) return BUILTIN_SCALARS[name]!;
    if (doc.enums.has(name)) return name;
    if (doc.unions.has(name)) return doc.unions.get(name)!.join(' | ');
    if (doc.scalars.has(name)) {
      if (/^(Date|DateTime|Time|Timestamp)$/i.test(name)) return 'string';
      return 'unknown';
    }
    if (doc.types.has(name)) return name;
    return 'unknown';
  })();
  return ref.nonNull ? inner : `${inner} | null`;
}

function argIsRequired(arg: GqlArg): boolean {
  return arg.type.nonNull && arg.defaultValue === undefined;
}

function commentOf(text: string | undefined): string | null {
  if (!text) return null;
  return text.replace(/\*\//g, '*\u200b/').replace(/\s+/g, ' ').trim();
}

function renderTypeRef(ref: GqlTypeRef): string {
  const inner = ref.kind === 'list' ? `[${renderTypeRef(ref.of!)}]` : ref.name!;
  return ref.nonNull ? `${inner}!` : inner;
}

function variablesInterfaceName(field: GqlField): string {
  return `${toPascalCase(field.name)}Variables`;
}

/** All type/enum names exported by types.ts (for type-only imports). */
function exportedTypeNames(doc: GqlDocument): string[] {
  return [...new Set([...doc.types.keys(), ...doc.enums.keys()])].sort();
}

function typeImportLine(doc: GqlDocument, importFrom: string): string {
  const names = exportedTypeNames(doc);
  if (names.length === 0) return '';
  return `import type { ${names.join(', ')} } from './types.js';`;
}

/* -------------------------------------------------------------------------- */
/* types.ts                                                                    */
/* -------------------------------------------------------------------------- */

function emitTypes(doc: GqlDocument, origin: string): string {
  const lines: string[] = [];
  lines.push(`// Auto-generated by contractful-gen from ${origin} — DO NOT EDIT.`);
  lines.push(`// Nullable GraphQL fields map to \`T | null\`; unknown custom scalars map to \`unknown\`.`);
  lines.push('');

  for (const [name, values] of [...doc.enums.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`export type ${name} =`);
    for (const value of values) lines.push(`  | ${JSON.stringify(value)}`);
    lines.push(';');
    lines.push('');
  }

  const objectTypes = [...doc.types.values()].sort((a, b) => a.name.localeCompare(b.name));
  for (const type of objectTypes) {
    const description = commentOf(type.description);
    if (description) lines.push(`/** ${description} */`);
    lines.push(`export interface ${type.name} {`);
    for (const field of type.fields) {
      const fieldDescription = commentOf(field.description);
      if (fieldDescription) lines.push(`  /** ${fieldDescription} */`);
      lines.push(`  ${field.name}${field.type.nonNull ? '' : '?'}: ${tsTypeOf(field.type, doc)};`);
    }
    lines.push('}');
    lines.push('');
  }

  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  lines.push('');
  return lines.join('\n');
}

/* -------------------------------------------------------------------------- */
/* Selections                                                                  */
/* -------------------------------------------------------------------------- */

/** Resolves a type ref to a named type present in the document, if any. */
function resolveNamed(ref: GqlTypeRef): string | undefined {
  return ref.kind === 'list' ? resolveNamed(ref.of!) : ref.name;
}

function isObjectLike(ref: GqlTypeRef, doc: GqlDocument): boolean {
  const name = resolveNamed(ref);
  return name !== undefined && (doc.types.has(name) || doc.unions.has(name));
}

const TYPENAME_FIELD: GqlField = {
  name: '__typename',
  type: { kind: 'named', name: 'String', nonNull: true },
  args: [],
};

/**
 * Builds the selection for an object-like ref. Returns `undefined` when the
 * ref is scalar-like or when the depth budget / cycle guard cuts it.
 */
function buildSelection(
  ref: GqlTypeRef,
  doc: GqlDocument,
  depth: number,
  path: Set<string>,
): SelectionNode[] | undefined {
  const name = resolveNamed(ref);
  if (name === undefined) return undefined;
  if (BUILTIN_SCALARS[name] !== undefined || doc.scalars.has(name)) return undefined;

  const union = doc.unions.get(name);
  if (union) return [{ field: TYPENAME_FIELD }];

  const type = doc.types.get(name);
  if (!type) return undefined;
  if (depth <= 0 || path.has(name)) return undefined;

  const children: SelectionNode[] = [];
  for (const field of type.fields) {
    if (field.deprecated) continue;
    const child = buildSelection(field.type, doc, depth - 1, new Set([...path, name]));
    // Object-typed fields whose selection was cut are omitted entirely.
    if (isObjectLike(field.type, doc) && !child) continue;
    children.push({ field, children: child?.length ? child : undefined });
  }
  return children;
}

/**
 * Renders a selection. Args are only rendered for fields whose variables
 * are declared in the operation definition (root fields).
 */
function renderSelection(nodes: SelectionNode[], indent: string, declaredArgs: Set<string>): string {
  const lines: string[] = [];
  for (const node of nodes) {
    const renderedArgs = node.field.args.filter((arg) => declaredArgs.has(arg.name));
    const args =
      renderedArgs.length > 0
        ? `(${renderedArgs.map((arg) => `${arg.name}: $${arg.name}`).join(', ')})`
        : '';
    if (node.children) {
      lines.push(`${indent}${node.field.name}${args} {`);
      lines.push(renderSelection(node.children, `${indent}  `, declaredArgs));
      lines.push(`${indent}}`);
    } else {
      lines.push(`${indent}${node.field.name}${args}`);
    }
  }
  return lines.join('\n');
}

/* -------------------------------------------------------------------------- */
/* Result types                                                                */
/* -------------------------------------------------------------------------- */

interface ResultTypeContext {
  doc: GqlDocument;
  /** Interfaces discovered while rendering; flushed after each operation. */
  pending: Map<string, SelectionNode>;
}

function resultTypeOf(node: SelectionNode, ctx: ResultTypeContext): string {
  return resultTypeOfRef(node.field.type, node, ctx);
}

function resultTypeOfRef(ref: GqlTypeRef, node: SelectionNode, ctx: ResultTypeContext): string {
  if (ref.kind === 'list') {
    const element = resultTypeOfRef(ref.of!, node, ctx);
    return ref.nonNull ? `Array<${element}>` : `Array<${element}> | null`;
  }
  const name = ref.name!;
  let base: string;
  if (BUILTIN_SCALARS[name] !== undefined) {
    base = BUILTIN_SCALARS[name]!;
  } else if (docHas(ctx.doc, name)) {
    const interfaceName = selectionInterfaceName(node.field.name);
    ctx.pending.set(interfaceName, node);
    base = node.children ? interfaceName : 'unknown';
  } else if (ctx.doc.enums.has(name)) {
    base = name;
  } else if (ctx.doc.unions.has(name)) {
    base = 'string'; // __typename selection
  } else {
    base = 'unknown';
  }
  return ref.nonNull ? base : `${base} | null`;
}

function docHas(doc: GqlDocument, name: string): boolean {
  return doc.types.has(name);
}

function selectionInterfaceName(fieldName: string): string {
  return `${toPascalCase(fieldName)}Selection`;
}

function renderResultInterface(
  nodes: SelectionNode[],
  interfaceName: string,
  ctx: ResultTypeContext,
): string {
  const lines: string[] = [`export interface ${interfaceName} {`];
  for (const node of nodes) {
    const inner = node.children ? resultTypeOf(node, ctx) : tsTypeOf(node.field.type, ctx.doc);
    lines.push(`  ${node.field.name}${node.field.type.nonNull ? '' : '?'}: ${inner};`);
  }
  lines.push('}');
  return lines.join('\n');
}

/** Drains the pending nested-selection interfaces (including discoveries). */
function flushPendingInterfaces(lines: string[], ctx: ResultTypeContext): void {
  const emitted = new Set<string>();
  let progress = true;
  while (progress && ctx.pending.size > 0) {
    progress = false;
    for (const [name, node] of [...ctx.pending.entries()]) {
      if (emitted.has(name)) continue;
      ctx.pending.delete(name);
      emitted.add(name);
      lines.push('');
      lines.push(renderResultInterface(node.children ?? [], name, ctx));
      progress = true;
    }
  }
}

/* -------------------------------------------------------------------------- */
/* client.ts                                                                   */
/* -------------------------------------------------------------------------- */

function emitClient(
  doc: GqlDocument,
  importFrom: string,
  base: string,
  maxDepth: number,
  origin: string,
): string {
  const ctx: ResultTypeContext = { doc, pending: new Map() };
  const operations: Array<{ field: GqlField; kind: 'query' | 'mutation'; root: string }> = [
    ...doc.queries.map((field) => ({ field, kind: 'query' as const, root: doc.roots.query ?? 'Query' })),
    ...doc.mutations.map((field) => ({ field, kind: 'mutation' as const, root: doc.roots.mutation ?? 'Mutation' })),
  ];

  const lines: string[] = [];
  lines.push(`// Auto-generated by contractful-gen from ${origin} — DO NOT EDIT.`);
  lines.push(`// Queries and mutations execute depth-capped full selections through the`);
  lines.push(`// contractful-ts HTTP transport; non-empty GraphQL error arrays throw.`);
  lines.push('');
  lines.push(`import { AxiosTransport, GraphQLError, HttpStatusError, type Transport } from ${JSON.stringify(importFrom)};`);
  const typeImport = typeImportLine(doc, importFrom);
  if (typeImport) lines.push(typeImport);
  lines.push('');
  lines.push(`export interface ClientOptions {`);
  lines.push(`  /** GraphQL endpoint. Default: ${JSON.stringify(base)} */`);
  lines.push(`  base?: string;`);
  lines.push(`  /** Custom transport (testing hook). */`);
  lines.push(`  transport?: Transport;`);
  lines.push(`  headers?: Record<string, string>;`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function createClient(options: ClientOptions = {}) {`);
  lines.push(`  const transport = options.transport ?? new AxiosTransport();`);
  lines.push(`  const base = options.base ?? ${JSON.stringify(base)};`);
  lines.push('');
  lines.push(`  async function execute<T>(operation: {`);
  lines.push(`    query: string;`);
  lines.push(`    variables: object | undefined;`);
  lines.push(`    rootField: string;`);
  lines.push(`  }): Promise<T> {`);
  lines.push(`    const res = await transport.send({`);
  lines.push(`      method: 'POST',`);
  lines.push(`      url: base,`);
  lines.push(`      headers: { 'content-type': 'application/json', ...(options.headers ?? {}) },`);
  lines.push(`      query: new URLSearchParams(),`);
  lines.push(`      body: { query: operation.query, variables: operation.variables as Record<string, unknown> | undefined },`);
  lines.push(`    });`);
  lines.push(`    const body = res.body as { data?: Record<string, unknown>; errors?: unknown[] } | undefined;`);
  lines.push(`    if (res.status >= 400) {`);
  lines.push(`      throw new HttpStatusError(\`GraphQL endpoint answered \${res.status}\`, { status: res.status, body });`);
  lines.push(`    }`);
  lines.push(`    if (body?.errors && body.errors.length > 0) throw new GraphQLError(body.errors);`);
  lines.push(`    return (body?.data?.[operation.rootField] ?? null) as T;`);
  lines.push(`  }`);
  lines.push('');
  lines.push(`  return {`);

  for (const { field } of operations) {
    const needsVariables = field.args.length > 0;
    lines.push(`    async ${field.name}(${needsVariables ? `variables: ${variablesInterfaceName(field)}` : 'variables?: undefined'}): Promise<${toPascalCase(field.name)}Result | null> {`);
    lines.push(`      return execute({ query: DOCUMENT_${toPascalCase(field.name)}, variables, rootField: ${JSON.stringify(field.name)} });`);
    lines.push(`    },`);
  }

  lines.push(`  };`);
  lines.push(`}`);
  lines.push('');

  // Variables interfaces.
  for (const { field } of operations) {
    if (field.args.length === 0) continue;
    lines.push(`export interface ${variablesInterfaceName(field)} {`);
    for (const arg of field.args) {
      const description = commentOf(arg.description);
      if (description) lines.push(`  /** ${description} */`);
      // Optional variables are omittable, not nullable.
      const type = argIsRequired(arg)
        ? tsTypeOf(arg.type, doc)
        : tsTypeOf({ ...arg.type, nonNull: true }, doc);
      lines.push(`  ${arg.name}${argIsRequired(arg) ? '' : '?'}: ${type};`);
    }
    lines.push(`}`);
    lines.push('');
  }

  // Documents + result interfaces.
  for (const { field, kind, root } of operations) {
    const selection = buildSelection({ kind: 'named', name: root, nonNull: true }, doc, maxDepth, new Set()) ?? [];
    const declaredArgs = new Set(field.args.map((arg) => arg.name));
    const varDefs =
      field.args.length > 0
        ? `(${field.args.map((arg) => `$${arg.name}: ${renderTypeRef(arg.type)}`).join(', ')})`
        : '';
    lines.push(`const DOCUMENT_${toPascalCase(field.name)} = \`${kind} ${toPascalCase(field.name)}${varDefs} {`);
    lines.push(renderSelection(selection, '  ', declaredArgs));
    lines.push('}`;');
    lines.push('');
  }

  for (const { field, root } of operations) {
    const selection = buildSelection({ kind: 'named', name: root, nonNull: true }, doc, maxDepth, new Set()) ?? [];
    lines.push(renderResultInterface(selection, `${toPascalCase(field.name)}Result`, ctx));
    flushPendingInterfaces(lines, ctx);
    lines.push('');
  }

  return lines.join('\n');
}

/* -------------------------------------------------------------------------- */
/* subscriptions.ts                                                            */
/* -------------------------------------------------------------------------- */

function emitSubscriptions(
  doc: GqlDocument,
  importFrom: string,
  eventsImport: string,
  wsUrl: string,
  maxDepth: number,
  origin: string,
): string {
  const ctx: ResultTypeContext = { doc, pending: new Map() };
  const root = doc.roots.subscription ?? 'Subscription';
  const eventsImportSpecifier = JSON.stringify(eventsImport);

  const lines: string[] = [];
  lines.push(`// Auto-generated by contractful-gen from ${origin} — DO NOT EDIT.`);
  lines.push(`// Subscriptions speak graphql-transport-ws over the contractful-ts events runtime.`);
  lines.push('');
  lines.push(`import { createGraphQLWsClient } from ${eventsImportSpecifier};`);
  lines.push(`import type { SocketFactory } from ${eventsImportSpecifier};`);
  const typeImport = typeImportLine(doc, importFrom);
  if (typeImport) lines.push(typeImport);
  lines.push('');
  lines.push(`export interface SubscriptionsOptions {`);
  lines.push(`  /** WebSocket endpoint. Default: ${JSON.stringify(wsUrl)} */`);
  lines.push(`  url?: string;`);
  lines.push(`  /** Payload merged into connection_init — auth tokens live here. */`);
  lines.push(`  connectionInitPayload?: unknown;`);
  lines.push(`  socketFactory?: SocketFactory;`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function createSubscriptions(options: SubscriptionsOptions = {}) {`);
  lines.push(`  const client = createGraphQLWsClient({`);
  lines.push(`    url: options.url ?? ${JSON.stringify(wsUrl)},`);
  lines.push(`    connectionInitPayload: options.connectionInitPayload,`);
  lines.push(`    socketFactory: options.socketFactory,`);
  lines.push(`  });`);
  lines.push('');
  lines.push(`  return {`);
  lines.push(`    connect: () => client.connect(),`);
  lines.push(`    disconnect: (code?: number, reason?: string) => client.disconnect(code, reason),`);
  lines.push('');

  for (const field of doc.subscriptions) {
    const needsVariables = field.args.length > 0;
    lines.push(`    ${field.name}(`);
    lines.push(`      ${needsVariables ? `variables: ${variablesInterfaceName(field)}, ` : ''}handlers: {`);
    lines.push(`        next: (data: ${toPascalCase(field.name)}Result | null) => void;`);
    lines.push(`        error?: (errors: unknown) => void;`);
    lines.push(`        complete?: () => void;`);
    lines.push(`      },`);
    lines.push(`    ) {`);
    lines.push(`      return client.subscribe(`);
    lines.push(`        { query: DOCUMENT_${toPascalCase(field.name)}${needsVariables ? ', variables: variables as unknown as Record<string, unknown> | undefined' : ''} },`);
    lines.push(`        {`);
    lines.push(`          next: (payload) => handlers.next(`);
    lines.push(`            ((payload as { data?: Record<string, unknown> }).data?.[${JSON.stringify(field.name)}] as ${toPascalCase(field.name)}Result | null | undefined) ?? null,`);
    lines.push(`          ),`);
    lines.push(`          error: handlers.error,`);
    lines.push(`          complete: handlers.complete,`);
    lines.push(`        },`);
    lines.push(`      );`);
    lines.push(`    },`);
    lines.push('');
  }

  lines.push(`  };`);
  lines.push(`}`);
  lines.push('');

  // Documents.
  for (const field of doc.subscriptions) {
    const selection =
      buildSelection({ kind: 'named', name: root, nonNull: true }, doc, maxDepth, new Set()) ?? [];
    const declaredArgs = new Set(field.args.map((arg) => arg.name));
    const varDefs =
      field.args.length > 0
        ? `(${field.args.map((arg) => `$${arg.name}: ${renderTypeRef(arg.type)}`).join(', ')})`
        : '';
    lines.push(`const DOCUMENT_${toPascalCase(field.name)} = \`subscription ${toPascalCase(field.name)}${varDefs} {`);
    lines.push(renderSelection(selection, '  ', declaredArgs));
    lines.push('}`;');
    lines.push('');
  }

  // Variables + result interfaces.
  for (const field of doc.subscriptions) {
    if (field.args.length === 0) continue;
    lines.push(`export interface ${variablesInterfaceName(field)} {`);
    for (const arg of field.args) {
      lines.push(`  ${arg.name}${argIsRequired(arg) ? '' : '?'}: ${tsTypeOf(arg.type, doc)};`);
    }
    lines.push(`}`);
    lines.push('');
  }

  for (const field of doc.subscriptions) {
    const selection =
      buildSelection({ kind: 'named', name: root, nonNull: true }, doc, maxDepth, new Set()) ?? [];
    const fieldSelection = selection.find((node) => node.field.name === field.name);
    if (!fieldSelection?.children) continue;
    lines.push(renderResultInterface(fieldSelection.children, `${toPascalCase(field.name)}Result`, ctx));
    flushPendingInterfaces(lines, ctx);
    lines.push('');
  }

  return lines.join('\n');
}
