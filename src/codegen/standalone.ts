export function emitStandaloneEvents(ir: EventsIR, options: StandaloneEmitOptions = {}): EmittedFile[] {
  const files: EmittedFile[] = [];
  for (const group of ir.groups) {
    if (group.channels.length === 0) continue;
    files.push({ path: group.fileName, content: emitStandaloneEventsGroup(ir, group, options) });
  }
  if (files.length > 0) {
    files.push({ path: '_ws.ts', content: WS_HELPER });
    files.push({
      path: 'index.ts',
      content: [
        `// Auto-generated by contractful-gen from ${options.specOrigin ?? 'spec'} — DO NOT EDIT.`,
        ...files.map((file) => `export * from './${file.path.replace(/\.ts$/, '')}.js';`),
        '',
      ].join('\n'),
    });
  }
  return files;
}

function messageInterfaceName(channelName: string): string {
  // Strip the direction prefix so interfaces read `OrderCreatedMessage`
  // rather than `OnOrderCreatedMessage`.
  const stripped = channelName.replace(/^(on|publish)(?=[A-Z])/, '');
  return `${toPascalCase(stripped)}Message`;
}

function emitStandaloneEventsGroup(
  ir: EventsIR,
  group: ChannelGroupIR,
  options: StandaloneEmitOptions,
): string {
  const factoryName = `create${toPascalCase(group.name)}Events`;
  const lines: string[] = [];

  lines.push(`// Auto-generated by contractful-gen from ${options.specOrigin ?? 'spec'} — DO NOT EDIT.`);
  lines.push(`// Standalone emit: typed events over a dependency-free WebSocket mini-runtime.`);
  lines.push(`// Events: ${ir.title} · url: ${ir.url}`);
  lines.push('');
  lines.push(`import { createEventsConnection, type SocketLike } from './_ws.js';`);
  lines.push('');

  // Message interfaces.
  for (const channel of group.channels) {
    if (channel.fields.length === 0) continue;
    lines.push(`export interface ${messageInterfaceName(channel.name)} {`);
    for (const field of channel.fields) {
      lines.push(`  ${field.tsName}${field.required ? '' : '?'}: ${tsTypeForParam(field)};`);
    }
    lines.push(`}`);
    lines.push('');
  }

  lines.push(`export interface ${toPascalCase(group.name)}EventsOptions {`);
  lines.push(`  url?: string;`);
  lines.push(`  socketFactory?: (url: string, protocols: string[]) => SocketLike | Promise<SocketLike>;`);
  lines.push(`  tokenProvider?: () => string | Promise<string>;`);
  lines.push(`  /** Query-parameter auth (default) — the only mode browsers guarantee. */`);
  lines.push(`  authQueryParameter?: string;`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function ${factoryName}(options: ${toPascalCase(group.name)}EventsOptions = {}) {`);
  lines.push(`  const connection = createEventsConnection({`);
  lines.push(`    url: options.url ?? ${JSON.stringify(ir.url)},`);
  lines.push(`    socketFactory: options.socketFactory,`);
  lines.push(`    tokenProvider: options.tokenProvider,`);
  lines.push(`    authQueryParameter: options.authQueryParameter,`);
  lines.push(`  });`);
  lines.push('');
  lines.push(`  return {`);
  lines.push(`    connect: () => connection.connect(),`);
  lines.push(`    disconnect: (code?: number, reason?: string) => connection.disconnect(code, reason),`);
  lines.push('');

  for (const channel of group.channels) {
    const messageTypeName =
      channel.fields.length > 0 ? messageInterfaceName(channel.name) : 'unknown';
    if (channel.direction === 'in') {
      lines.push(`    ${channel.name}(handler: (message: ${messageTypeName}, ctx: { topic: string | null; params: Record<string, string> }) => void) {`);
      lines.push(`      return connection.subscribe(${JSON.stringify(channel.topic)}, (message, ctx) => handler(message as ${messageTypeName}, ctx));`);
      lines.push(`    },`);
    } else {
      const hasParams = channel.params.length > 0;
      lines.push(`    async ${channel.name}(${hasParams ? `message: ${messageTypeName}, params: { ${channel.params.map((p) => `${p.tsName}${p.required ? '' : '?'}: string`).join('; ')} }` : `message: ${messageTypeName}`}) {`);
      if (hasParams) {
        lines.push(`      const topic = \`${
          channel.topic.replace(/:([A-Za-z0-9_]+)/g, (_m, name: string) => `\${params.${name} ?? ''}`)
        }\`;`);
        lines.push(`      await connection.publish(topic, message);`);
      } else {
        lines.push(`      await connection.publish(${JSON.stringify(channel.topic)}, message);`);
      }
      lines.push(`    },`);
    }
    lines.push('');
  }

  lines.push(`  };`);
  lines.push(`}`);
  lines.push('');
  return lines.join('\n');
}

const WS_HELPER = `// Dependency-free WebSocket mini-runtime for standalone event clients.
// Connect with automatic reconnect, JSON { topic, payload } envelopes and
// pattern routing (":param" segments and the "*" wildcard).

export interface SocketLike {
  send(data: string): void;
  close(code?: number, reason?: string): void;
  // Handler params are any so browser WebSocket / ws / Socket.IO sockets
  // assign without casts.
  onopen: ((event: any) => void) | null;
  onmessage: ((event: any) => void) | null;
  onclose: ((event: any) => void) | null;
  onerror: ((event: any) => void) | null;
}

export type SocketFactory = (url: string, protocols: string[]) => SocketLike | Promise<SocketLike>;

export interface EventsConnection {
  connect(): Promise<void>;
  disconnect(code?: number, reason?: string): Promise<void>;
  subscribe(pattern: string, handler: (message: unknown, ctx: { topic: string | null; params: Record<string, string> }) => void): () => void;
  publish(topic: string, message: unknown): Promise<void>;
}

interface Subscription {
  pattern: string;
  handler: (message: unknown, ctx: { topic: string | null; params: Record<string, string> }) => void;
}

export function matchTopic(pattern: string, topic: string | null): Record<string, string> | null {
  if (pattern === '*') return {};
  if (topic === null) return null;
  if (pattern === topic) return {};
  const a = pattern.split('/');
  const b = topic.split('/');
  if (a.length !== b.length) return null;
  const params: Record<string, string> = {};
  for (let i = 0; i < a.length; i++) {
    const p = a[i]!;
    const t = b[i]!;
    if (p.startsWith(':') && p.length > 1) {
      params[p.slice(1)] = t;
    } else if (p !== '*' && p !== t) {
      return null;
    }
  }
  return params;
}

export function createEventsConnection(options: {
  url: string;
  socketFactory?: SocketFactory;
  tokenProvider?: () => string | Promise<string>;
  authQueryParameter?: string;
  reconnectMaxAttempts?: number;
  reconnectBaseDelayMs?: number;
}): EventsConnection {
  const subscriptions = new Set<Subscription>();
  let socket: SocketLike | null = null;
  let state: 'idle' | 'connecting' | 'open' | 'closed' | 'failed' = 'idle';
  let attempts = 0;
  let userClosed = false;
  let reconnectTimer: ReturnType<typeof setTimeout> | null = null;
  let openWaiters: Array<() => void> = [];

  function makeSocket(): Promise<SocketLike> {
    const factory =
      options.socketFactory ??
      ((url: string) => {
        const Ctor = (globalThis as { WebSocket?: new (url: string) => SocketLike }).WebSocket;
        if (!Ctor) throw new Error('No WebSocket implementation found; pass socketFactory.');
        return new Ctor(url);
      });
    return Promise.resolve(
      factory(options.url, []),
    ).then(async (created) => {
      if (options.tokenProvider) {
        // Rebuild the URL with a fresh token per attempt.
        const token = await options.tokenProvider();
        const param = options.authQueryParameter ?? 'access_token';
        const url = \`\${options.url}\${options.url.includes('?') ? '&' : '?'}\${param}=\${encodeURIComponent(token)}\`;
        return factory(url, []);
      }
      return created;
    });
  }

  function route(data: unknown): void {
    if (typeof data !== 'string' || data.length === 0) return;
    let frame: unknown;
    try {
      frame = JSON.parse(data);
    } catch {
      return;
    }
    const record = typeof frame === 'object' && frame !== null ? (frame as Record<string, unknown>) : null;
    const topic =
      record && (typeof record.topic === 'string' || typeof record.event === 'string')
        ? ((record.topic as string) ?? (record.event as string))
        : null;
    const payload = record && 'payload' in record ? record.payload : record && 'data' in record ? record.data : frame;
    for (const sub of [...subscriptions]) {
      const params = matchTopic(sub.pattern, topic);
      if (params === null) continue;
      sub.handler(payload, { topic, params });
    }
  }

  function settleOpen(): void {
    const waiters = openWaiters;
    openWaiters = [];
    for (const waiter of waiters) waiter();
  }

  async function attempt(): Promise<void> {
    state = 'connecting';
    try {
      const created = await makeSocket();
      if (userClosed) {
        try {
          created.close();
        } catch {
          /* ignore */
        }
        return;
      }
      socket = created;
      created.onopen = () => {
        attempts = 0;
        state = 'open';
        settleOpen();
      };
      created.onmessage = (event: { data: unknown }) => route(event.data);
      created.onclose = () => {
        socket = null;
        if (userClosed) {
          state = 'closed';
          return;
        }
        if (attempts < (options.reconnectMaxAttempts ?? 10)) {
          attempts++;
          state = 'connecting';
          reconnectTimer = setTimeout(() => {
            reconnectTimer = null;
            void attempt();
          }, (options.reconnectBaseDelayMs ?? 250) * attempts);
        } else {
          state = 'failed';
        }
      };
      created.onerror = null;
    } catch {
      if (userClosed) return;
      if (attempts < (options.reconnectMaxAttempts ?? 10)) {
        attempts++;
        reconnectTimer = setTimeout(() => {
          reconnectTimer = null;
          void attempt();
        }, (options.reconnectBaseDelayMs ?? 250) * attempts);
      } else {
        state = 'failed';
      }
    }
  }

  return {
    connect(): Promise<void> {
      if (state === 'open') return Promise.resolve();
      if (state === 'connecting') {
        return new Promise<void>((resolve) => openWaiters.push(resolve));
      }
      userClosed = false;
      attempts = 0;
      void attempt();
      return new Promise<void>((resolve) => openWaiters.push(resolve));
    },
    disconnect(code = 1000, reason = 'client closed'): Promise<void> {
      userClosed = true;
      if (reconnectTimer) {
        clearTimeout(reconnectTimer);
        reconnectTimer = null;
      }
      if (socket) {
        try {
          socket.close(code, reason);
        } catch {
          /* ignore */
        }
      } else {
        state = 'closed';
      }
      return Promise.resolve();
    },
    subscribe(pattern, handler) {
      const sub = { pattern, handler };
      subscriptions.add(sub);
      return () => subscriptions.delete(sub);
    },
    async publish(topic, message) {
      if (state !== 'open' || !socket) throw new Error(\`Events connection is \${state}\`);
      socket.send(JSON.stringify({ topic, payload: message }));
    },
  };
}
`;
