/**
 * Standalone emitters — self-contained generated clients with **zero
 * imports from contractful-ts**.
 *
 * - `emitStandaloneHttp`: per group, a `createXxxApi({ baseUrl, headers,
 *   fetchImpl })` factory with typed argument interfaces. A tiny shared
 *   `_http.ts` (fetch-based, ~60 lines) is emitted once per output root.
 * - `emitStandaloneEvents`: per group, a `createXxxEvents({ url,
 *   socketFactory })` factory with typed message interfaces, backed by a
 *   shared `_ws.ts` mini-runtime (connect, reconnect, JSON envelope
 *   routing) that uses the global WebSocket or an injected factory.
 *
 * Trade-off vs `emit: 'runtime'`: no validation, retries, circuit breaking
 * or rate limiting — types only. Generated GraphQL sources cannot use
 * standalone mode for subscriptions.
 */

import type { ApiGroupIR, ApiIR, OperationIR, ParamIR } from './openapi.js';
import { toPascalCase } from './openapi.js';
import type { ChannelGroupIR, EventsIR } from './model.js';
import type { EmittedFile } from './emitter.js';

export interface StandaloneEmitOptions {
  specOrigin?: string;
}

/* -------------------------------------------------------------------------- */
/* HTTP                                                                        */
/* -------------------------------------------------------------------------- */

export function emitStandaloneHttp(ir: ApiIR, options: StandaloneEmitOptions = {}): EmittedFile[] {
  const files: EmittedFile[] = [];
  for (const group of ir.groups) {
    if (group.operations.length === 0) continue;
    files.push({
      path: group.fileName,
      content: emitStandaloneGroup(ir, group, options),
    });
  }
  if (files.length > 0) {
    files.push({ path: '_http.ts', content: HTTP_HELPER });
    files.push({
      path: 'index.ts',
      content: [
        `// Auto-generated by contractful-gen from ${options.specOrigin ?? 'spec'} — DO NOT EDIT.`,
        ...files.map((file) => `export * from './${file.path.replace(/\.ts$/, '')}.js';`),
        '',
      ].join('\n'),
    });
  }
  return files;
}

function tsTypeForParam(param: ParamIR): string {
  switch (param.schema.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      return 'unknown[]';
    case 'object':
      return 'Record<string, unknown>';
    default:
      return 'string';
  }
}

function argsInterfaceName(op: OperationIR): string {
  return `${toPascalCase(op.name)}Args`;
}

function responseTypeOf(op: OperationIR): string {
  const declared = op.responds.find((r) => r.status >= 200 && r.status < 300) ?? op.responds[0];
  switch (declared?.type) {
    case 'array':
      return 'unknown[]';
    case 'hash':
      return 'Record<string, unknown>';
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    default:
      return 'unknown';
  }
}

function emitStandaloneGroup(ir: ApiIR, group: ApiGroupIR, options: StandaloneEmitOptions): string {
  const constName = `${group.constName.replace(/Api$/, '')}StandaloneApi`;
  const factoryName = `create${toPascalCase(group.name)}Api`;
  const lines: string[] = [];

  lines.push(`// Auto-generated by contractful-gen from ${options.specOrigin ?? 'spec'} — DO NOT EDIT.`);
  lines.push(`// Standalone emit: no runtime dependency. Types only — no validation, retries or circuit breaking.`);
  lines.push(`// API: ${ir.title} · group: ${group.name} · base: ${ir.base}`);
  lines.push('');
  lines.push(`import { request, ApiError } from './_http.js';`);
  lines.push('');

  // Argument interfaces.
  for (const op of group.operations) {
    if (op.params.length === 0) continue;
    lines.push(`export interface ${argsInterfaceName(op)} {`);
    for (const param of op.params) {
      lines.push(`  ${param.tsName}${param.required ? '' : '?'}: ${tsTypeForParam(param)};`);
    }
    lines.push(`}`);
    lines.push('');
  }

  lines.push(`export interface ${constName}Options {`);
  lines.push(`  baseUrl?: string;`);
  lines.push(`  headers?: Record<string, string>;`);
  lines.push(`  fetchImpl?: typeof fetch;`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function ${factoryName}(options: ${constName}Options = {}) {`);
  lines.push(`  const baseUrl = options.baseUrl ?? ${JSON.stringify(ir.base)};`);
  lines.push('');
  lines.push(`  return {`);

  for (const op of group.operations) {
    const hasArgs = op.params.length > 0;
    lines.push(`    async ${op.name}(${hasArgs ? `args: ${argsInterfaceName(op)}` : ''}): Promise<${responseTypeOf(op)}> {`);

    // Path interpolation.
    const pathExpr = op.path.includes(':')
      ? `\`${op.path.replace(/:([A-Za-z0-9_]+)/g, (_m, name: string) => `\${encodeURIComponent(String(args.${name}))}`)}\``
      : JSON.stringify(op.path);

    const queryParams = op.params.filter((p) => p.location === 'query');
    const bodyParams = op.params.filter((p) => p.location === 'body');
    const headerParams = op.params.filter((p) => p.location === 'header');

    if (queryParams.length > 0) {
      lines.push(`      const query = new URLSearchParams();`);
      for (const param of queryParams) {
        lines.push(`      if (args.${param.tsName} !== undefined) query.set(${JSON.stringify(param.wireName)}, String(args.${param.tsName}));`);
      }
    }
    if (bodyParams.length > 0) {
      lines.push(`      const body: Record<string, unknown> = {};`);
      for (const param of bodyParams) {
        lines.push(`      if (args.${param.tsName} !== undefined) body[${JSON.stringify(param.wireName)}] = args.${param.tsName};`);
      }
    }
    if (headerParams.length > 0) {
      lines.push(`      const headers: Record<string, string> = { ...(options.headers ?? {}) };`);
      for (const param of headerParams) {
        lines.push(`      if (args.${param.tsName} !== undefined) headers[${JSON.stringify(param.wireName)}] = String(args.${param.tsName});`);
      }
    }

    lines.push(`      return request({`);
    lines.push(`        method: ${JSON.stringify(op.method)},`);
    if (headerParams.length === 0) {
      lines.push(`        headers: options.headers,`);
    } else {
      lines.push(`        headers,`);
    }
    lines.push(`        baseUrl,`);
    lines.push(`        fetchImpl: options.fetchImpl,`);
    const querySlot = queryParams.length > 0 ? 'query' : 'undefined';
    const bodySlot = bodyParams.length > 0 ? ', body' : '';
    lines.push(`      }, ${pathExpr}, ${querySlot}${bodySlot});`);
    lines.push(`    },`);
  }

  lines.push(`  };`);
  lines.push(`}`);
  lines.push('');
  return lines.join('\n');
}

const HTTP_HELPER = `// Shared helper for standalone clients — no external dependencies.
export class ApiError extends Error {
  readonly status: number;
  readonly body: unknown;
  constructor(status: number, body: unknown) {
    super(\`HTTP \${status}\`);
    this.name = 'ApiError';
    this.status = status;
    this.body = body;
  }
}

export async function request<T = unknown>(
  init: {
    method: string;
    headers?: Record<string, string>;
    baseUrl: string;
    fetchImpl?: typeof fetch;
  },
  path: string,
  query?: URLSearchParams,
  body?: Record<string, unknown>,
): Promise<T> {
  const doFetch = init.fetchImpl ?? fetch;
  const url = \`\${init.baseUrl.replace(/\\/+$/, '')}\${path}\${query && query.size > 0 ? \`?\${query.toString()}\` : ''}\`;
  const res = await doFetch(url, {
    method: init.method,
    headers: {
      ...(body !== undefined ? { 'content-type': 'application/json' } : {}),
      ...(init.headers ?? {}),
    },
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  const parsed = text.length > 0 ? safeJson(text) : undefined;
  if (!res.ok) throw new ApiError(res.status, parsed);
  return parsed as T;
}

function safeJson(text: string): unknown {
  try {
    return JSON.parse(text);
  } catch {
    return text;
  }
}
`;

